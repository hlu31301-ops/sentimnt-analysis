-- 1. 감성 분석 로그 테이블 생성
CREATE TABLE IF NOT EXISTS sentiment_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    input_text TEXT NOT NULL,
    sentiment VARCHAR(20) NOT NULL,
    confidence INTEGER NOT NULL CHECK (confidence >= 0 AND confidence <= 100),
    reason TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. 최신순 조회를 위한 인덱스 생성
CREATE INDEX IF NOT EXISTS idx_sentiment_logs_created_at 
ON sentiment_logs (created_at DESC);

-- 3. 테이블 및 컬럼 설명
COMMENT ON TABLE sentiment_logs IS 'MoodLens 사용자 텍스트 감성 분석 결과 로그 테이블';
COMMENT ON COLUMN sentiment_logs.id IS '기록 고유 식별 번호 (PK)';
COMMENT ON COLUMN sentiment_logs.input_text IS '사용자가 입력한 텍스트 본문';
COMMENT ON COLUMN sentiment_logs.sentiment IS '감정 상태 분류 (긍정/부정/중립)';
COMMENT ON COLUMN sentiment_logs.confidence IS '분석 신뢰도 백분율 (0-100)';
COMMENT ON COLUMN sentiment_logs.reason IS 'AI 모델이 도출한 감정 분석 이유';
COMMENT ON COLUMN sentiment_logs.created_at IS '데이터가 저장된 생성 시각 (UTC)';

-- 4. 행 단위 보안(RLS) 활성화 및 안전 정책 설정
ALTER TABLE sentiment_logs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Service role full access policy" ON sentiment_logs;
CREATE POLICY "Service role full access policy"
ON sentiment_logs
FOR ALL
TO service_role
USING (true)
WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anonymous insert policy" ON sentiment_logs;
CREATE POLICY "Allow anonymous insert policy"
ON sentiment_logs
FOR INSERT
TO anon
WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anonymous select policy" ON sentiment_logs;
CREATE POLICY "Allow anonymous select policy"
ON sentiment_logs
FOR SELECT
TO anon
USING (true);

